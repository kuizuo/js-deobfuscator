const messages: Record<Locale, Record<TranslationKey, string>> = {
  'en': english,
  'zh-CN': chinese,
}

const storedLocale = useLocalStorage<string>('js-deobfuscator:locale', 'en')

export const locale = computed<Locale>({
  get: () => storedLocale.value === 'zh-CN' ? 'zh-CN' : 'en',
  set: value => storedLocale.value = value,
})

export function toggleLocale() {
  locale.value = locale.value === 'en' ? 'zh-CN' : 'en'
}

export function t(key: TranslationKey, values: Record<string, string | number> = {}) {
  const message = messages[locale.value][key] ?? english[key]
  return Object.entries(values).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    message,
  )
}
